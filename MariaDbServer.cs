// MariaDbServer.cs
// ─────────────────────────────────────────────────────────────────────────────
// Manages the MariaDB server process (mysqld.exe) and handles first-run
// database initialisation.
//
// MariaDB lifecycle:
//   1. First run: InitialiseDataDirectory() creates the system databases
//      in the data directory. This only runs once.
//   2. Every run: Start() launches mysqld.exe pointing at the data directory.
//   3. Stop() sends a graceful shutdown signal, then force-kills if needed.
//
// Why we run mysqld.exe directly (not as a Windows Service):
//   Registering a Windows Service requires administrator privileges.
//   Running mysqld.exe as a child process of WINSERV requires none.
//   The trade-off: the database is only available while WINSERV is open.
//   For a developer tool this is exactly the right behaviour.
// ─────────────────────────────────────────────────────────────────────────────

using System.Diagnostics;

namespace WINSERV;

/// <summary>
/// Manages the MariaDB server process and first-run data directory initialisation.
/// </summary>
public class MariaDbServer : ProcessWrapper
{
    private readonly AppConfig _config;

    public MariaDbServer(AppConfig config)
    {
        _config = config;
    }

    // ── ProcessWrapper Overrides ─────────────────────────────────────────────

    public override string ServiceName => "MariaDB";

    protected override string ExecutablePath => _config.MariaDbExePath;

    /// <summary>
    /// Builds arguments for mysqld.exe.
    ///
    /// We pass a --defaults-file pointing at our generated my.ini, which
    /// contains the data directory, port, and character set settings.
    /// This is safer than passing all settings on the command line.
    /// </summary>
    protected override string BuildArguments()
    {
        return $"--defaults-file=\"{_config.MariaDbMyIniPath}\"";
    }

    // ── MariaDB-Specific Methods ─────────────────────────────────────────────

    /// <summary>
    /// Returns true if the MariaDB data directory has been initialised.
    /// We check for 'mysql' subfolder, which is the system schema created
    /// by mysql_install_db / --initialize.
    /// </summary>
    public bool IsDataDirectoryInitialised()
    {
        return Directory.Exists(Path.Combine(_config.DataDirectory, "mysql"));
    }

    /// <summary>
    /// Writes a my.ini configuration file for this MariaDB instance.
    /// This is always regenerated (not just on first run) so changes to
    /// HttpPort, DataDirectory etc. in the config are reflected on next start.
    /// </summary>
    public void WriteMyIni()
    {
        OnOutputReceived("[MariaDB] Writing my.ini...", isError: false);

        // The MariaDB share directory contains the error message files and
        // character set data that mysqld needs. It lives inside the mariadb
        // portable folder.
        string mariaDbBaseDir = Path.Combine(_config.InstallPath, "mariadb");
        string shareDir       = Path.Combine(mariaDbBaseDir, "share");

        // In my.ini, the [mysqld] section contains server-side settings.
        // Paths with backslashes: MariaDB accepts forward slashes on Windows,
        // which avoids the need to double-escape backslashes.
        // We call .Replace(@"\", "/") on all paths for this reason.
        string iniContent = $@"; my.ini — generated by WINSERV
; Edit this file to customise MariaDB behaviour.
; Restart MariaDB after making changes.

[mysqld]

; ── Paths ─────────────────────────────────────────────────────────────────────
; basedir: root of the MariaDB installation (the extracted mariadb folder)
basedir   = {mariaDbBaseDir.Replace(@"\", "/")}

; datadir: where database files (tables, logs) are stored
datadir   = {_config.DataDirectory.Replace(@"\", "/")}

; lc-messages-dir: where MariaDB finds its error message files
lc-messages-dir = {shareDir.Replace(@"\", "/")}

; ── Network ───────────────────────────────────────────────────────────────────
; Only listen on localhost — never accessible from other machines on the network.
bind-address = 127.0.0.1
port         = {_config.MariaDbPort}

; ── Character Set ─────────────────────────────────────────────────────────────
; utf8mb4 supports the full Unicode range including emoji (unlike plain utf8).
character-set-server  = utf8mb4
collation-server      = utf8mb4_unicode_ci

; ── Logging ───────────────────────────────────────────────────────────────────
; Log errors to a file instead of stdout so we can review them later.
log_error = {Path.Combine(_config.LogDirectory, "mariadb_error.log").Replace(@"\", "/")}

; ── InnoDB ────────────────────────────────────────────────────────────────────
; InnoDB is the default storage engine (supports transactions, foreign keys).
; This buffer pool size is appropriate for a dev machine.
innodb_buffer_pool_size = 64M

; ── Authentication ────────────────────────────────────────────────────────────
; Force mysql_native_password so PHP mysqli/PDO can connect without GSSAPI.
; MariaDB 12 on Windows defaults to GSSAPI/SSPI which PHP does not support.
; 'default_authentication_plugin' is the correct MariaDB directive (not
; 'authentication_plugin', which is MySQL-only and causes mysqld to abort).
default_authentication_plugin = mysql_native_password

; ── Performance ───────────────────────────────────────────────────────────────
; Skip reverse DNS lookups on connections — speeds up connection setup.
skip-name-resolve

[client]
; Default client settings (used by mysql.exe command-line tool)
port         = {_config.MariaDbPort}
";

        Directory.CreateDirectory(Path.GetDirectoryName(_config.MariaDbMyIniPath)!);
        File.WriteAllText(_config.MariaDbMyIniPath, iniContent);
        OnOutputReceived($"[MariaDB] my.ini written to {_config.MariaDbMyIniPath}", isError: false);
    }

    /// <summary>
    /// Initialises the MariaDB data directory on first run using mysql_install_db.exe.
    /// This creates the system tables and sets the root password in one step.
    /// Returns true on success, false on failure.
    /// </summary>
    public bool InitialiseDataDirectory()
    {
        if (IsDataDirectoryInitialised())
        {
            OnOutputReceived("[MariaDB] Data directory already initialised — skipping.", isError: false);
            return true;
        }

        OnOutputReceived("[MariaDB] Initialising data directory (first run)...", isError: false);

        Directory.CreateDirectory(_config.DataDirectory);
        Directory.CreateDirectory(_config.LogDirectory);

        WriteMyIni();

        if (!File.Exists(_config.MariaDbInstallDbPath))
        {
            OnOutputReceived($"[MariaDB] mysql_install_db.exe not found at {_config.MariaDbInstallDbPath}", isError: true);
            return false;
        }

        // mysql_install_db.exe creates the data directory. We don't pass a password
        // here because on MariaDB 12 for Windows it creates root with GSSAPI auth
        // regardless of the --password flag. We fix the auth plugin in the next step.
        string initArgs = $"--datadir=\"{_config.DataDirectory}\"";

        OnOutputReceived($"[MariaDB] Running: mysql_install_db.exe {initArgs}", isError: false);

        bool ok = RunProcess(_config.MariaDbInstallDbPath, initArgs, timeoutSeconds: 120);

        if (!ok)
        {
            OnOutputReceived("[MariaDB] Initialisation failed. Check the log output above.", isError: true);
            return false;
        }

        OnOutputReceived("[MariaDB] Data directory created. Setting root password and auth plugin...", isError: false);

        // MariaDB 12 on Windows creates root with GSSAPI auth by default, which
        // PHP's mysqli does not support. We start mysqld briefly with
        // --skip-grant-tables (bypasses auth entirely), connect as root,
        // switch to mysql_native_password, and set the password.
        bool passwordOk = SetRootAuthOnFirstRun();
        if (!passwordOk)
            OnOutputReceived("[MariaDB] Warning: could not set root password — you may need to set it manually.", isError: true);

        OnOutputReceived("[MariaDB] Data directory initialised successfully.", isError: false);
        return true;
    }

    /// <summary>
    /// Starts mysqld with --skip-grant-tables, connects with mysql.exe, and
    /// runs ALTER USER to switch root to mysql_native_password + set the password.
    /// This is the only reliable way to fix the GSSAPI default auth on Windows.
    /// </summary>
    private bool SetRootAuthOnFirstRun()
    {
        string skipGrantArgs = $"--defaults-file=\"{_config.MariaDbMyIniPath}\" --skip-grant-tables";

        using var mysqld = new Process
        {
            StartInfo = new ProcessStartInfo
            {
                FileName               = _config.MariaDbExePath,
                Arguments              = skipGrantArgs,
                UseShellExecute        = false,
                CreateNoWindow         = true,
                RedirectStandardOutput = true,
                RedirectStandardError  = true,
            }
        };

        try
        {
            mysqld.Start();
            mysqld.BeginOutputReadLine();
            mysqld.BeginErrorReadLine();

            bool ready = WaitForPort(_config.MariaDbPort, timeoutSeconds: 30);
            if (!ready)
            {
                OnOutputReceived("[MariaDB] Timed out waiting for mysqld during auth setup.", isError: true);
                mysqld.Kill();
                return false;
            }

            // Fix auth for both 'localhost' (named pipe) and '127.0.0.1' (TCP).
            // With skip-name-resolve in my.ini, TCP clients are matched by IP only,
            // so root@'localhost' alone is not enough for Navicat / PHP over TCP.
            // FLUSH PRIVILEGES is required before ALTER USER when --skip-grant-tables is active.
            string pwd = EscapeSql(_config.MariaDbRootPassword);
            string sql = "FLUSH PRIVILEGES; " +
                         $"ALTER USER 'root'@'localhost' IDENTIFIED VIA mysql_native_password USING PASSWORD('{pwd}'); " +
                         $"GRANT ALL PRIVILEGES ON *.* TO 'root'@'127.0.0.1' IDENTIFIED VIA mysql_native_password USING PASSWORD('{pwd}') WITH GRANT OPTION; " +
                         "FLUSH PRIVILEGES;";

            bool sqlOk = RunProcess(
                _config.MariaDbClientPath,
                $"--host=127.0.0.1 --port={_config.MariaDbPort} --user=root --execute=\"{sql}\"",
                timeoutSeconds: 15);

            // Shut down the temporary mysqld. After FLUSH PRIVILEGES re-enables
            // auth, we must supply the password. Always force-kill as a fallback
            // so the port is guaranteed free before normal startup begins.
            string mysqladminPath = Path.Combine(
                Path.GetDirectoryName(_config.MariaDbExePath)!, "mysqladmin.exe");

            if (File.Exists(mysqladminPath))
            {
                RunProcess(mysqladminPath,
                    $"--host=127.0.0.1 --port={_config.MariaDbPort} --user=root " +
                    $"--password=\"{pwd}\" shutdown",
                    timeoutSeconds: 10);
            }

            // Always kill + wait to guarantee the port is free, even if
            // mysqladmin succeeded (graceful shutdown can be slow).
            if (!mysqld.HasExited)
            {
                mysqld.Kill();
            }
            mysqld.WaitForExit(5000);

            // Windows does not release a killed process's listening socket the
            // instant it terminates. The real mysqld starts immediately after
            // this method returns and binds the same port — without this wait
            // it can lose that race and fail with WSAEACCES (10013), which
            // looks like "MariaDB won't start" even though nothing is wrong.
            WaitForPortFree(_config.MariaDbPort, timeoutSeconds: 10);

            return sqlOk;
        }
        catch (Exception ex)
        {
            OnOutputReceived($"[MariaDB] Error during auth setup: {ex.Message}", isError: true);
            try { mysqld.Kill(); } catch { }
            return false;
        }
    }

    /// <summary>
    /// Polls localhost:port until a TCP connection succeeds or the timeout expires.
    /// </summary>
    private static bool WaitForPort(int port, int timeoutSeconds)
    {
        var deadline = DateTime.UtcNow.AddSeconds(timeoutSeconds);
        while (DateTime.UtcNow < deadline)
        {
            try
            {
                using var client = new System.Net.Sockets.TcpClient();
                if (client.ConnectAsync("127.0.0.1", port).Wait(500))
                    return true;
            }
            catch { }
            Thread.Sleep(500);
        }
        return false;
    }

    /// <summary>
    /// Polls localhost:port until nothing accepts a connection there, or the
    /// timeout expires. Used after force-killing mysqld: TerminateProcess does
    /// not guarantee Windows has released the listening socket immediately, so
    /// starting a new mysqld on the same port right away can fail to bind with
    /// WSAEACCES (10013) even though the old process is gone.
    /// </summary>
    private static bool WaitForPortFree(int port, int timeoutSeconds)
    {
        var deadline = DateTime.UtcNow.AddSeconds(timeoutSeconds);
        while (DateTime.UtcNow < deadline)
        {
            try
            {
                using var client = new System.Net.Sockets.TcpClient();
                if (client.ConnectAsync("127.0.0.1", port).Wait(300) && client.Connected)
                {
                    Thread.Sleep(200);
                    continue;
                }
                return true;
            }
            catch
            {
                return true;
            }
        }
        return false;
    }

    /// <summary>
    /// Launches a process, captures its output to our log, and waits for it
    /// to exit. Returns true if the exit code is 0 (success).
    /// </summary>
    private bool RunProcess(string exe, string args, int timeoutSeconds)
    {
        using var p = new Process
        {
            StartInfo = new ProcessStartInfo
            {
                FileName               = exe,
                Arguments              = args,
                UseShellExecute        = false,
                CreateNoWindow         = true,
                RedirectStandardOutput = true,
                RedirectStandardError  = true,
            }
        };

        p.OutputDataReceived += (_, e) => { if (e.Data != null) OnOutputReceived(e.Data, false); };
        p.ErrorDataReceived  += (_, e) => { if (e.Data != null) OnOutputReceived(e.Data, true); };

        p.Start();
        p.BeginOutputReadLine();
        p.BeginErrorReadLine();

        bool exited = p.WaitForExit(timeoutSeconds * 1000);

        if (!exited)
        {
            p.Kill();
            return false;
        }

        return p.ExitCode == 0;
    }

    /// <summary>
    /// Minimal SQL string escaping: escapes single quotes to prevent
    /// a password containing a quote from breaking the SQL string.
    /// This is NOT a full SQL injection defence — it's used only for
    /// the local setup command where the value comes from our own config.
    /// </summary>
    private static string EscapeSql(string value)
    {
        return value.Replace("'", "\\'");
    }
}
